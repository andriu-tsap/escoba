function validateForm(form){
  const lang=localStorage.getItem('escoba_lang')||'pl';
  let firstInvalid=null;
  form.querySelectorAll('[required]').forEach(el=>{
    el.setCustomValidity('');
    const empty = el.type==='file' ? !(el.files&&el.files.length) : !el.value.trim();
    if(empty){
      el.setCustomValidity(T[lang].required_msg);
      if(!firstInvalid) firstInvalid=el;
    }else if(el.type==='email' && !el.validity.valid){
      el.setCustomValidity(T[lang].email_msg);
      if(!firstInvalid) firstInvalid=el;
    }
  });
  if(firstInvalid){ firstInvalid.reportValidity(); return false; }
  return true;
}
document.querySelectorAll('form').forEach(form=>{
  form.setAttribute('novalidate','novalidate');
  form.addEventListener('submit',e=>{ if(!validateForm(form)) e.preventDefault(); });
  form.querySelectorAll('[required]').forEach(el=>el.addEventListener('input',()=>el.setCustomValidity('')));
});
